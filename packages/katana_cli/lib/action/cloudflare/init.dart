/// Cloudflare Wrangler.jsonc codebase.
///
/// Cloudflare Wrangler.jsoncのコードベース。
class CloudflareWranglerCliCode extends CliCode {
  /// Cloudflare Wrangler.jsonc codebase.
  ///
  /// Cloudflare Wrangler.jsoncのコードベース。
  const CloudflareWranglerCliCode({
    required this.projectId,
    this.smartPlacement = false,
    this.main = "src/edge.ts",
    this.placementRegion,
    this.includeAssets = true,
  });

  /// Worker entrypoint relative to `cloudflare/`.
  ///
  /// `cloudflare/`からの相対パスで指定するWorkerのエントリファイル。
  final String main;

  /// Fixed placement region such as `aws:us-east-1`.
  /// If specified, Smart Placement settings are not output.
  ///
  /// `aws:us-east-1`などの固定placementリージョン。
  /// 指定した場合、Smart Placementの設定は出力されません。
  final String? placementRegion;

  /// Whether to output the static assets (`./public`) settings.
  ///
  /// 静的アセット（`./public`）の設定を出力するかどうか。
  final bool includeAssets;

  /// Project ID.
  /// This is required to set the project ID in wrangler.jsonc.
  ///
  /// CloudflareのプロジェクトID。
  /// wrangler.jsoncにプロジェクトIDを設定するために必要です。
  final String projectId;

  /// Whether to enable Cloudflare Workers Smart Placement.
  ///
  /// Cloudflare WorkersのSmart Placementを有効にするかどうか。
  final bool smartPlacement;

  @override
  String get name => "wrangler";

  @override
  String get prefix => "wrangler";

  @override
  String get directory => "cloudflare";

  @override
  String get description =>
      "Define the code for wrangler.jsonc in Cloudflare. Cloudflareのwrangler.jsoncのコードを定義します。";

  @override
  String import(String path, String baseName, String className) {
    return """
""";
  }

  @override
  String header(String path, String baseName, String className) {
    return "";
  }

  @override
  String body(String path, String baseName, String className) {
    return """
/**
 * For more details on how to configure Wrangler, refer to:
 * https://developers.cloudflare.com/workers/wrangler/configuration/
 */
{
	"\$schema": "node_modules/wrangler/config-schema.json",
	"name": "$projectId",
	"main": "$main",
	"compatibility_date": "2026-06-29",
	"compatibility_flags": [
		"nodejs_compat",
		"global_fetch_strictly_public"
	],${includeAssets ? """
	"assets": {
		// The path to the directory containing the `index.html` file to be served at `/`
		"directory": "./public"
	},""" : ""}
	"observability": {
		"logs": {
			"enabled": true,
			"invocation_logs": true
		},
		"traces": {
			"enabled": true
		}
	},
	"upload_source_maps": true,
	${placementRegion != null ? '"placement": { "region": ${jsonEncode(placementRegion)} },' : smartPlacement ? '"placement": { "mode": "smart" },' : '''
	/**
	 * Smart Placement
	 * https://developers.cloudflare.com/workers/configuration/smart-placement/#smart-placement
	 */
	// "placement": {  "mode": "smart" }'''}
	/**
	 * Bindings
	 * Bindings allow your Worker to interact with resources on the Cloudflare Developer Platform, including
	 * databases, object storage, AI inference, real-time communication and more.
	 * https://developers.cloudflare.com/workers/runtime-apis/bindings/
	 */
	/**
	 * Environment Variables
	 * https://developers.cloudflare.com/workers/wrangler/configuration/#environment-variables
	 * Note: Use secrets to store sensitive data.
	 * https://developers.cloudflare.com/workers/configuration/secrets/
	 */
	// "vars": {  "MY_VARIABLE": "production_value" }
	/**
	 * Service Bindings (communicate between multiple Workers)
	 * https://developers.cloudflare.com/workers/wrangler/configuration/#service-bindings
	 */
	// "services": [  {   "binding": "MY_SERVICE",   "service": "my-service"  } ]
}
""";
  }
}
