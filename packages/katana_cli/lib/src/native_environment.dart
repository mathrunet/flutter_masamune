import "dart:convert";
import "dart:io";

/// Configures Android Gradle to read Katana's native build environment from
/// Flutter's `DART_DEFINES` project property.
class AndroidNativeEnvironmentSynchronizer {
  const AndroidNativeEnvironmentSynchronizer._();

  /// Beginning of the managed Gradle section.
  static const beginMarker = "// KATANA NATIVE ENVIRONMENT BEGIN";

  /// End of the managed Gradle section.
  static const endMarker = "// KATANA NATIVE ENVIRONMENT END";

  /// Beginning of the managed Firebase section.
  static const firebaseBeginMarker = "// KATANA FIREBASE ENVIRONMENT BEGIN";

  /// End of the managed Firebase section.
  static const firebaseEndMarker = "// KATANA FIREBASE ENVIRONMENT END";

  /// Adds dev/prod validation and optional Android application ID switching.
  ///
  /// `ANDROID_APPLICATION_ID` is optional. When omitted, the application ID
  /// already present in Gradle remains the effective value.
  static String synchronize(String source, {required bool isKotlin}) {
    if (source.contains(beginMarker)) {
      return isKotlin ? _migrateKotlinBase64(source) : source;
    }
    final applicationIdPattern = isKotlin
        ? RegExp(
            r'''applicationId\s*=\s*(?:katanaAndroidApplicationId\s*\?:\s*)?(["'][^"']+["'])''',
          )
        : RegExp(
            r'''applicationId\s*(?:=\s*)?(?:katanaAndroidApplicationId\s*\?:\s*)?(["'][^"']+["'])''',
          );
    final match = applicationIdPattern.firstMatch(source);
    if (match == null) {
      throw const FormatException("Android applicationId was not found.");
    }
    final originalApplicationId = match.group(1)!;
    final androidIndex =
        RegExp(r"^android\s*\{", multiLine: true).firstMatch(source)?.start;
    if (androidIndex == null) {
      throw const FormatException("Android Gradle block was not found.");
    }
    final block = isKotlin ? _kotlinBlock : _groovyBlock;
    var result = source.replaceRange(androidIndex, androidIndex, "$block\n\n");
    result = result.replaceFirst(
      applicationIdPattern,
      isKotlin
          ? "applicationId = katanaAndroidApplicationId ?: $originalApplicationId"
          : "applicationId katanaAndroidApplicationId ?: $originalApplicationId",
    );
    if (isKotlin) {
      result = _ensureKotlinBase64Import(result);
    }
    return result;
  }

  /// Configures Google Services tasks to consume the selected environment.
  static String synchronizeFirebase(String source, {required bool isKotlin}) {
    if (source.contains(firebaseBeginMarker)) {
      return source;
    }
    if (!source.contains(beginMarker)) {
      throw const FormatException(
        "Katana native environment must be configured before Firebase.",
      );
    }
    final block = isKotlin ? _kotlinFirebaseBlock : _groovyFirebaseBlock;
    return "$source\n$block";
  }

  /// Replaces the fully qualified decoder generated by older versions.
  ///
  /// Gradle Kotlin DSL resolves `java` to the project's Java extension, so
  /// `java.util.Base64` does not compile in build scripts.
  static String _migrateKotlinBase64(String source) {
    const legacy = "java.util.Base64.getDecoder()";
    if (!source.contains(legacy)) {
      return source;
    }
    return _ensureKotlinBase64Import(
      source.replaceAll(legacy, "Base64.getDecoder()"),
    );
  }

  static String _ensureKotlinBase64Import(String source) {
    if (RegExp(r"^import java\.util\.Base64[ \t]*$", multiLine: true)
        .hasMatch(source)) {
      return source;
    }
    return "import java.util.Base64\n$source";
  }

  static const _kotlinBlock = '''
$beginMarker
val katanaDartDefines =
    ((project.findProperty("dart-defines") ?: project.findProperty("DART_DEFINES")) as? String)
        ?.split(",")
        ?.filter { it.isNotBlank() }
        ?.associate { encoded ->
            val decoded = String(Base64.getDecoder().decode(encoded))
            val separator = decoded.indexOf('=')
            if (separator < 0) decoded to "" else decoded.substring(0, separator) to decoded.substring(separator + 1)
        }
        ?: emptyMap()
val katanaFlavor = katanaDartDefines["FLAVOR"]
    ?: throw GradleException("FLAVOR must be specified with --dart-define-from-file.")
if (katanaFlavor !in setOf("dev", "prod")) {
    throw GradleException("FLAVOR must be dev or prod: \$katanaFlavor")
}
val katanaAndroidApplicationId = katanaDartDefines["ANDROID_APPLICATION_ID"]
$endMarker
''';

  static const _groovyBlock = '''
$beginMarker
def katanaDartDefines = (project.findProperty("dart-defines") ?: project.findProperty("DART_DEFINES") ?: "")
    .split(",")
    .findAll { !it.isEmpty() }
    .collectEntries { encoded ->
        def decoded = new String(java.util.Base64.decoder.decode(encoded), "UTF-8")
        def separator = decoded.indexOf('=')
        separator < 0 ? [(decoded): ""] : [(decoded.substring(0, separator)): decoded.substring(separator + 1)]
    }
def katanaFlavor = katanaDartDefines["FLAVOR"]
if (katanaFlavor == null) {
    throw new GradleException("FLAVOR must be specified with --dart-define-from-file.")
}
if (!(katanaFlavor in ["dev", "prod"])) {
    throw new GradleException("FLAVOR must be dev or prod: \$katanaFlavor")
}
def katanaAndroidApplicationId = katanaDartDefines["ANDROID_APPLICATION_ID"]
$endMarker
''';

  static const _kotlinFirebaseBlock = '''
$firebaseBeginMarker
afterEvaluate {
    tasks.matching { it.name.endsWith("GoogleServices") }.configureEach {
        val selectedGoogleServices =
            file("src/katanaFirebase/\$katanaFlavor/google-services.json")
        if (!selectedGoogleServices.exists()) {
            throw GradleException(
                "Firebase configuration is missing for FLAVOR=\$katanaFlavor: \${selectedGoogleServices.path}",
            )
        }
        val setter = javaClass.methods.firstOrNull {
            it.name == "setGoogleServicesJsonFiles" && it.parameterCount == 1
        } ?: throw GradleException(
            "The Google Services plugin does not expose googleServicesJsonFiles.",
        )
        setter.invoke(this, listOf(selectedGoogleServices))
    }
}
$firebaseEndMarker
''';

  static const _groovyFirebaseBlock = '''
$firebaseBeginMarker
afterEvaluate {
    tasks.matching { it.name.endsWith("GoogleServices") }.configureEach {
        def selectedGoogleServices =
            file("src/katanaFirebase/\${katanaFlavor}/google-services.json")
        if (!selectedGoogleServices.exists()) {
            throw new GradleException(
                "Firebase configuration is missing for FLAVOR=\${katanaFlavor}: \${selectedGoogleServices.path}"
            )
        }
        def setter = getClass().methods.find {
            it.name == "setGoogleServicesJsonFiles" && it.parameterCount == 1
        }
        if (setter == null) {
            throw new GradleException(
                "The Google Services plugin does not expose googleServicesJsonFiles."
            )
        }
        setter.invoke(delegate, [selectedGoogleServices])
    }
}
$firebaseEndMarker
''';
}

/// Configures an Apple Runner target to select Firebase plist by `FLAVOR`.
class AppleFirebaseEnvironmentSynchronizer {
  const AppleFirebaseEnvironmentSynchronizer._();

  /// Stable build phase identifier used in generated Xcode projects.
  static const buildPhaseId = "F17EBA5E0000000000000001";

  /// Display name of the generated build phase.
  static const buildPhaseName = "Select Katana Firebase Configuration";

  /// Creates the shell script invoked by the Xcode build phase.
  static String get shellScript => r'''
#!/bin/sh
set -eu

FLAVOR=""
OLD_IFS="$IFS"
IFS=','
for encoded in ${DART_DEFINES:-}; do
  decoded="$(printf '%s' "$encoded" | /usr/bin/base64 -D)"
  case "$decoded" in
    FLAVOR=*) FLAVOR="${decoded#FLAVOR=}" ;;
  esac
done
IFS="$OLD_IFS"

case "$FLAVOR" in
  test)
    destination_dir="$TARGET_BUILD_DIR/$UNLOCALIZED_RESOURCES_FOLDER_PATH"
    if [ -d "$destination_dir" ]; then
      (cd "$destination_dir" && /bin/rm -f GoogleService-Info.plist)
    fi
    exit 0 ;;
  dev|prod) ;;
  *) echo "error: FLAVOR must be test, dev or prod." >&2; exit 1 ;;
esac

firebase_root="$PROJECT_DIR/Runner/Firebase"
if [ ! -d "$firebase_root" ]; then
  exit 0
fi
source_plist="$firebase_root/$FLAVOR/GoogleService-Info.plist"
if [ ! -f "$source_plist" ]; then
  echo "error: Firebase configuration is missing for FLAVOR=$FLAVOR: $source_plist" >&2
  exit 1
fi
destination="$TARGET_BUILD_DIR/$UNLOCALIZED_RESOURCES_FOLDER_PATH/GoogleService-Info.plist"
/bin/mkdir -p "$(/usr/bin/dirname "$destination")"
/bin/cp "$source_plist" "$destination"
''';

  /// Adds an idempotent shell build phase to the Runner native target.
  static String synchronizeProject(String source) {
    source = _retireLegacyPlistReferences(source);
    source = _retireFlutterFireBundlePhases(source);
    final targets = RegExp(
      r"/\* Begin PBXNativeTarget section \*/[\s\S]*?/\* End PBXNativeTarget section \*/",
    ).firstMatch(source);
    if (targets == null) {
      throw const FormatException("The Xcode native targets were not found.");
    }
    var targetSection = targets.group(0)!.replaceAll(
          RegExp("^[ \\t]*$buildPhaseId /\\* $buildPhaseName \\*/,\\n",
              multiLine: true),
          "",
        );
    final runner = RegExp(
      r"[A-Z0-9]+ /\* Runner \*/ = \{\s*isa = PBXNativeTarget;[\s\S]*?buildPhases = \(\n",
    ).firstMatch(targetSection);
    if (runner == null) {
      throw const FormatException("The Runner Xcode target was not found.");
    }
    targetSection = targetSection.replaceRange(runner.end, runner.end,
        "\t\t\t\t$buildPhaseId /* $buildPhaseName */,\n");
    source = source.replaceRange(targets.start, targets.end, targetSection);
    final escapedScript = shellScript
        .replaceAll(r"\", r"\\")
        .replaceAll('"', r'\"')
        .replaceAll("\n", r"\n");
    final phasePattern = RegExp(
      "$buildPhaseId /\\* $buildPhaseName \\*/ = \\{[\\s\\S]*?\\n[ \\t]*\\};",
    );
    final existingPhase = phasePattern.firstMatch(source);
    if (existingPhase != null) {
      final updated = existingPhase.group(0)!.replaceFirst(
            RegExp(r'shellScript = "(?:\\.|[^"\\])*";'),
            'shellScript = "$escapedScript";',
          );
      return source.replaceRange(
          existingPhase.start, existingPhase.end, updated);
    }
    var result = source;
    const sectionEnd = "/* End PBXShellScriptBuildPhase section */";
    final sectionIndex = result.indexOf(sectionEnd);
    if (sectionIndex < 0) {
      throw const FormatException(
          "PBXShellScriptBuildPhase section was not found.");
    }
    final phase = '''
\t\t$buildPhaseId /* $buildPhaseName */ = {
\t\t\tisa = PBXShellScriptBuildPhase;
\t\t\talwaysOutOfDate = 1;
\t\t\tbuildActionMask = 2147483647;
\t\t\tfiles = ();
\t\t\tinputFileListPaths = ();
\t\t\tinputPaths = ();
\t\t\tname = "$buildPhaseName";
\t\t\toutputFileListPaths = ();
\t\t\toutputPaths = (
\t\t\t\t"\$(TARGET_BUILD_DIR)/\$(UNLOCALIZED_RESOURCES_FOLDER_PATH)/GoogleService-Info.plist",
\t\t\t);
\t\t\trunOnlyForDeploymentPostprocessing = 0;
\t\t\tshellPath = /bin/sh;
\t\t\tshellScript = "$escapedScript";
\t\t};
''';
    result = result.replaceRange(sectionIndex, sectionIndex, phase);
    return result;
  }

  /// Removes FlutterFire plist copying superseded by FLAVOR-based selection.
  static String _retireFlutterFireBundlePhases(String source) {
    final phases = RegExp(
      r"^[ \t]*([A-Z0-9]+) /\*[^\n]*\*/ = \{\n[ \t]*isa = PBXShellScriptBuildPhase;[\s\S]*?^[ \t]*\};",
      multiLine: true,
    ).allMatches(source).where((match) => RegExp(
          r'shellScript = "(?:\\.|[^"\\])*flutterfire bundle-service-file\b',
        ).hasMatch(match.group(0)!)).toList();
    for (final phase in phases.reversed) {
      source = source.replaceRange(phase.start, phase.end, "");
    }
    for (final phase in phases) {
      source = source.replaceAll(
        RegExp("^[ \\t]*${phase.group(1)} /\\*[^\\n]*\\*/,\\n",
            multiLine: true),
        "",
      );
    }
    return source;
  }

  /// Removes the root plist references superseded by the selection phase.
  static String _retireLegacyPlistReferences(String source) {
    final references = RegExp(
      r'^\s*([A-Z0-9]+) /\* GoogleService-Info\.plist \*/ = \{isa = PBXFileReference;[^\n]*path = "?(?:Runner/)?GoogleService-Info\.plist"?;[^\n]*\};[ \t]*$',
      multiLine: true,
    ).allMatches(source).map((match) => match.group(1)!).toSet();
    if (references.isEmpty) {
      return source;
    }
    final buildFiles = RegExp(
      r"^\s*([A-Z0-9]+) /\* GoogleService-Info\.plist in Resources \*/ = \{isa = PBXBuildFile; fileRef = ([A-Z0-9]+)[^\n]*\};[ \t]*$",
      multiLine: true,
    )
        .allMatches(source)
        .where((match) => references.contains(match.group(2)))
        .map((match) => match.group(1)!);
    final ids = {...references, ...buildFiles};
    return source
        .split("\n")
        .where((line) => !ids.any(
            (id) => RegExp("^\\s*$id /\\* GoogleService-Info").hasMatch(line)))
        .join("\n");
  }
}

/// Validates and applies opt-in application identities from `app.targets`.
///
/// Select targets under the same build lock used by the Flutter build. No
/// packages, Firebase registrations, or remote resources are changed.
class NativeAppTarget {
  const NativeAppTarget._();

  /// Validates all declarations and selects one local application target.
  static Future<void> apply(Map declarations, String selected) async {
    final namePattern = RegExp(r"^[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}$");
    final idPattern =
        RegExp(r"^[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z][A-Za-z0-9_]*)+$");
    if (!namePattern.hasMatch(selected) ||
        !declarations.containsKey(selected)) {
      throw const FormatException("Unknown or invalid native target.");
    }
    final targets = <String, Map<String, Object>>{};
    for (final declaration in declarations.entries) {
      final name = declaration.key;
      final data = declaration.value;
      if (name is! String ||
          !namePattern.hasMatch(name) ||
          data is! Map ||
          data.keys.any((key) => !const {
                "entrypoint",
                "application_id",
                "ios_bundle_id",
                "android_application_id",
                "ios_minimum_version",
                "ios_link_objc_categories"
              }.contains(key))) {
        throw const FormatException("Invalid app.targets declaration.");
      }
      final entry = data["entrypoint"];
      final common = data["application_id"];
      final ios = data["ios_bundle_id"] ?? common;
      final android = data["android_application_id"] ?? common;
      if (entry is! String ||
          !RegExp(r"^lib/(?:[A-Za-z0-9_-]+/)*[A-Za-z0-9_-]+\.dart$")
              .hasMatch(entry) ||
          ios is! String ||
          !idPattern.hasMatch(ios) ||
          android is! String ||
          !idPattern.hasMatch(android)) {
        throw const FormatException(
            "Targets require a lib entrypoint and valid platform identifiers.");
      }
      final minimumIos = data["ios_minimum_version"];
      if (minimumIos != null &&
          (minimumIos is! String ||
              !RegExp(r"^[0-9]{1,2}\.[0-9]{1,2}(?:\.[0-9]{1,2})?$")
                  .hasMatch(minimumIos))) {
        throw const FormatException(
            "ios_minimum_version must be a quoted iOS version (e.g. 15.5).");
      }
      final linkObjcCategories = data["ios_link_objc_categories"];
      if (linkObjcCategories != null && linkObjcCategories is! bool) {
        throw const FormatException(
            "ios_link_objc_categories must be a boolean.");
      }
      targets[name] = {
        "entrypoint": entry,
        "ios_bundle_id": ios,
        "android_application_id": android,
        if (minimumIos != null) "ios_minimum_version": minimumIos as String,
        if (linkObjcCategories != null)
          "ios_link_objc_categories": linkObjcCategories as bool
      };
    }
    final target = targets[selected]!;
    final entry = File(target["entrypoint"]! as String);
    _validatePath(entry.path);
    if (!entry.existsSync()) {
      throw const FormatException(
          "Selected entrypoint must exist inside lib without symlinks.");
    }
    final updates = <String, String>{};
    final project = File("ios/Runner.xcodeproj/project.pbxproj");
    if (project.existsSync()) {
      var count = 0;
      final source = project.readAsStringSync();
      final updated = source.replaceAllMapped(
        RegExp(
            r"(isa = XCBuildConfiguration;[\s\S]*?buildSettings = \{)([\s\S]*?)(\n[ \t]*\};[ \t\r\n]*name = [^;]+;)"),
        (match) {
          var settings = match[2]!;
          if (!RegExp(r'INFOPLIST_FILE = "?Runner/Info\.plist"?;')
              .hasMatch(settings)) {
            return match[0]!;
          }
          if (!RegExp(r"PRODUCT_BUNDLE_IDENTIFIER = [^;]+;")
              .hasMatch(settings)) {
            throw const FormatException(
                "Runner bundle identifier was not found.");
          }
          settings = settings.replaceFirst(
              RegExp(r"PRODUCT_BUNDLE_IDENTIFIER = [^;]+;"),
              r'PRODUCT_BUNDLE_IDENTIFIER = "$(KATANA_APPLICATION_ID)";');
          settings = settings.replaceAll(
              RegExp(r"\n[ \t]*FLUTTER_TARGET = [^;]+;"), "");
          settings = "${settings.trimRight()}\n\t\t\t\t"
              r'FLUTTER_TARGET = "$(KATANA_FLUTTER_TARGET)";';
          count++;
          return "${match[1]}$settings${match[3]}";
        },
      );
      if (count == 0) {
        throw const FormatException(
            "No supported Runner build configurations found.");
      }
      updates[project.path] = updated;
      var includes = 0;
      for (final mode in ["Debug", "Release", "Profile"]) {
        final file = File("ios/Flutter/$mode.xcconfig");
        if (!file.existsSync()) {
          continue;
        }
        final content = file.readAsStringSync();
        const include = '#include "KatanaTarget.xcconfig"';
        updates[file.path] =
            content.contains(include) ? content : "$content\n$include\n";
        includes++;
      }
      if (includes < 2) {
        throw const FormatException(
            "Flutter Debug/Release xcconfigs are required.");
      }
      updates["ios/Flutter/KatanaTarget.xcconfig"] =
          "// Generated by katana apply --only nativetarget --target $selected.\n"
          "KATANA_APPLICATION_ID = ${target['ios_bundle_id']}\n"
          "KATANA_FLUTTER_TARGET = ${target['entrypoint']}\n"
          "${target['ios_minimum_version'] == null ? '' : 'IPHONEOS_DEPLOYMENT_TARGET = ${target['ios_minimum_version']}\n'}"
          "${target['ios_link_objc_categories'] == true ? r'OTHER_LDFLAGS = $(inherited) -ObjC' '\n' : ''}";
      final podfile = File("ios/Podfile");
      if (podfile.existsSync()) {
        const begin = "# KATANA NATIVE TARGET IOS MINIMUM BEGIN";
        const end = "# KATANA NATIVE TARGET IOS MINIMUM END";
        final original = podfile.readAsStringSync();
        final cleaned = original.replaceAll(
            RegExp(
                "${RegExp.escape(begin)}\\n[\\s\\S]*?${RegExp.escape(end)}\\n"),
            "");
        final minimum = target["ios_minimum_version"];
        updates[podfile.path] = minimum == null
            ? cleaned
            : "$begin\nplatform :ios, '$minimum'\n$end\n$cleaned";
      }
    }
    for (final fileName in [
      "android/app/build.gradle.kts",
      "android/app/build.gradle"
    ]) {
      final file = File(fileName);
      if (!file.existsSync()) {
        continue;
      }
      final kotlin = fileName.endsWith(".kts");
      var gradle = AndroidNativeEnvironmentSynchronizer.synchronize(
          file.readAsStringSync(),
          isKotlin: kotlin);
      gradle = gradle
          .replaceAll('setOf("dev", "prod")', 'setOf("test", "dev", "prod")')
          .replaceAll('["dev", "prod"]', '["test", "dev", "prod"]');
      if (gradle
          .contains(AndroidNativeEnvironmentSynchronizer.firebaseBeginMarker)) {
        if (kotlin && !gradle.contains("return@configureEach")) {
          gradle = gradle.replaceFirst(
              "        val selectedGoogleServices =",
              '        if (katanaFlavor == "test") { enabled = false; return@configureEach }\n'
                  "        val selectedGoogleServices =");
        } else if (!kotlin && !gradle.contains('katanaFlavor == "test"')) {
          gradle = gradle.replaceFirst(
              "        def selectedGoogleServices =",
              '        if (katanaFlavor == "test") { enabled = false; return }\n'
                  "        def selectedGoogleServices =");
        }
      }
      gradle = gradle.replaceFirst(
          RegExp(r'''katanaAndroidApplicationId \?: ["'][^"']+["']'''),
          'katanaAndroidApplicationId ?: "${target['android_application_id']}"');
      updates[fileName] = gradle;
    }
    if (!project.existsSync() &&
        !File("android/app/build.gradle.kts").existsSync() &&
        !File("android/app/build.gradle").existsSync()) {
      throw const FormatException(
          "No supported native application project found.");
    }
    final yamlFile = File("katana.yaml");
    _validatePath(yamlFile.path);
    final digest =
        Process.runSync("openssl", ["dgst", "-sha256", yamlFile.path]);
    final hash = RegExp(r"[a-fA-F0-9]{64}$")
        .firstMatch(digest.stdout.toString().trim())
        ?.group(0);
    if (digest.exitCode != 0 || hash == null) {
      throw const FormatException(
          "Cannot fingerprint katana.yaml with openssl.");
    }
    final catalog = {
      "schema_version": 1,
      "selected": selected,
      "targets": targets,
      "katana_sha256": hash.toLowerCase()
    };
    updates[".katana/native_targets.json"] = "${jsonEncode(catalog)}\n";
    for (final update in updates.entries) {
      final file = File(update.key);
      _validatePath(file.path);
    }
    for (final update in updates.entries) {
      final file = File(update.key);
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(update.value);
    }
  }

  static void _validatePath(String path) {
    var current = Directory.current.resolveSymbolicLinksSync();
    for (final part in path.split("/")) {
      current = "$current/$part";
      if (FileSystemEntity.isLinkSync(current)) {
        throw const FormatException(
            "Native target paths must not traverse symlinks.");
      }
    }
  }
}
