// Dart imports:
import "dart:io";

/// Configures Android Gradle signing to prefer keystore values supplied by
/// environment variables, falling back to `android/key.properties`.
///
/// The keystore is decoded from [keystoreVariable] into the Gradle build
/// directory at configuration time, so no keystore file needs to be kept in
/// the project.
class AndroidSigningEnvironment {
  const AndroidSigningEnvironment._();

  /// Beginning of the managed Gradle section.
  static const beginMarker = "// KATANA SIGNING ENVIRONMENT BEGIN";

  /// End of the managed Gradle section.
  static const endMarker = "// KATANA SIGNING ENVIRONMENT END";

  /// Environment variable holding the base64 encoded keystore.
  static const keystoreVariable = "ANDROID_KEYSTORE_B64";

  /// Environment variable holding the store and key password.
  static const passwordVariable = "ANDROID_KEYSTORE_PASSWORD";

  /// Environment variable holding the key alias.
  static const aliasVariable = "ANDROID_KEYSTORE_ALIAS";

  /// Environment variable holding the base64 encoded Google Play service
  /// account key.
  static const serviceAccountVariable = "GPC_SERVICE_ACCOUNT_KEY_B64";

  /// Expression used for the signing config values generated by Katana.
  static const storeFileExpression = "katanaSigningStoreFile";

  /// Expression used for the store password generated by Katana.
  static const storePasswordExpression = "katanaSigningStorePassword";

  /// Expression used for the key password generated by Katana.
  static const keyPasswordExpression = "katanaSigningKeyPassword";

  /// Expression used for the key alias generated by Katana.
  static const keyAliasExpression = "katanaSigningKeyAlias";

  static final _blockRegExp = RegExp(
    "${RegExp.escape(beginMarker)}[\\s\\S]*?${RegExp.escape(endMarker)}\\n*",
  );

  /// Returns the value of [name] in [environment] when it is not blank.
  static String? value(String name, [Map<String, String>? environment]) {
    final value = (environment ?? Platform.environment)[name];
    if (value == null || value.trim().isEmpty) {
      return null;
    }
    return value;
  }

  /// Whether the keystore and its password are supplied by [environment].
  static bool isConfigured([Map<String, String>? environment]) {
    return value(keystoreVariable, environment) != null &&
        value(passwordVariable, environment) != null;
  }

  /// Returns the managed section contained in [source], if any.
  static String? extract(String source) {
    return _blockRegExp.firstMatch(source)?.group(0)?.trimRight();
  }

  /// Inserts or replaces the managed section in [source].
  ///
  /// [alias] is used as the last fallback for the key alias.
  /// The section must follow the `keyProperties` loader and is therefore
  /// placed directly before the `android` block.
  static String synchronize(
    String source, {
    required bool isKotlin,
    String alias = "",
  }) {
    var result = source.replaceAll(_blockRegExp, "");
    final androidIndex =
        RegExp(r"^android\s*\{", multiLine: true).firstMatch(result)?.start;
    if (androidIndex == null) {
      throw const FormatException("Android Gradle block was not found.");
    }
    final block = isKotlin ? _kotlinBlock(alias) : _groovyBlock(alias);
    result = result.replaceRange(androidIndex, androidIndex, "$block\n\n");
    if (isKotlin) {
      result = _ensureKotlinBase64Import(result);
    }
    return result;
  }

  static String _ensureKotlinBase64Import(String source) {
    if (RegExp(r"^import java\.util\.Base64[ \t]*$", multiLine: true)
        .hasMatch(source)) {
      return source;
    }
    return "import java.util.Base64\n$source";
  }

  static String _escape(String value) {
    return value
        .replaceAll(r"\", r"\\")
        .replaceAll('"', r'\"')
        .replaceAll(r"$", r"\$");
  }

  static String _kotlinBlock(String alias) {
    final aliasFallback = alias.isEmpty ? "" : ' ?: "${_escape(alias)}"';
    return '''
$beginMarker
fun katanaSigningEnv(name: String): String? = System.getenv(name)?.takeIf { it.isNotBlank() }
val $storeFileExpression: File? =
    katanaSigningEnv("$keystoreVariable")?.let { encoded ->
        layout.buildDirectory.file("signing/upload.keystore").get().asFile.also { file ->
            file.parentFile.mkdirs()
            file.writeBytes(Base64.getMimeDecoder().decode(encoded))
        }
    } ?: (keyProperties["storeFile"] as String?)?.let { File(rootProject.projectDir, "app/" + it) }
val $storePasswordExpression: String? = $storeFileExpression?.let {
    katanaSigningEnv("$passwordVariable") ?: keyProperties["storePassword"] as String?
}
val $keyPasswordExpression: String? = $storeFileExpression?.let {
    katanaSigningEnv("$passwordVariable") ?: keyProperties["keyPassword"] as String?
}
val $keyAliasExpression: String? = $storeFileExpression?.let {
    katanaSigningEnv("$aliasVariable") ?: keyProperties["keyAlias"] as String?$aliasFallback
}
$endMarker''';
  }

  static String _groovyBlock(String alias) {
    final aliasFallback = alias.isEmpty ? "" : ' ?: "${_escape(alias)}"';
    return '''
$beginMarker
def katanaSigningEnv = { String name ->
    def value = System.getenv(name)
    value != null && !value.trim().isEmpty() ? value : null
}
def $storeFileExpression = null
def katanaSigningKeystore = katanaSigningEnv("$keystoreVariable")
if (katanaSigningKeystore != null) {
    $storeFileExpression = layout.buildDirectory.file("signing/upload.keystore").get().asFile
    $storeFileExpression.parentFile.mkdirs()
    $storeFileExpression.bytes = java.util.Base64.mimeDecoder.decode(katanaSigningKeystore)
} else if (keyProperties['storeFile'] != null) {
    $storeFileExpression = file(keyProperties['storeFile'])
}
def $storePasswordExpression = $storeFileExpression == null ? null : (katanaSigningEnv("$passwordVariable") ?: keyProperties['storePassword'])
def $keyPasswordExpression = $storeFileExpression == null ? null : (katanaSigningEnv("$passwordVariable") ?: keyProperties['keyPassword'])
def $keyAliasExpression = $storeFileExpression == null ? null : (katanaSigningEnv("$aliasVariable") ?: keyProperties['keyAlias']$aliasFallback)
$endMarker''';
  }
}
